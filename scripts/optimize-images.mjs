import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile, stat, unlink } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = fileURLToPath(new URL("../", import.meta.url));
const originals = [
  ...[
    "degree_certificate.png",
    "engineer.png",
    "network.png",
    "facebook_marketing.jpeg",
    "MicrosoftAI.png",
    "sessac.png",
    "vr_content_certificate.jpg",
  ].map((file) => ({ source: `credentials/${file}`, width: 960 })),
  ...[
    "졸업사진.webp",
    "금산_2.webp",
    "버추얼2기_1.jpg",
    "행사_1.jpg",
    "금산_5.jpg",
    "태안_3.webp",
    "태안_7.jpg",
    "태안_4.webp",
    "금산_6.webp",
    "행사_3.jpg",
    "태안_5.webp",
    "금산_7.jpg",
    "버추얼2기_2.JPG",
    "행사_4.jpg",
  ].map((file) => ({ source: `coverletter/${file}`, width: 480 })),
  { source: "images/working.png", width: 640 },
  { source: "images/cafe/0.jpeg", width: 1440 },
  ...[
    "images/dev/InteractiveRacing/1.png",
    "jinu/14.png",
    "images/dev/gracesea/project-thumbnail.jpg",
    "images/gamingroom/1.jpeg",
  ].map((source) => ({ source, width: 640 })),
];
const output = path.join(root, "public/images/previews");
await mkdir(output, { recursive: true });
const manifestPath = path.join(root, "src/app/data/imagePreviews.json");
let previousManifest = {};
try {
  previousManifest = JSON.parse(await readFile(manifestPath, "utf8"));
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}
const manifest = {};
let originalBytes = 0;
let previewBytes = 0;
for (const { source, width } of originals) {
  const original = path.join(root, "public", source);
  const input = await readFile(original);
  const hash = createHash("sha256")
    .update(source)
    .update(input)
    .update(String(width))
    .digest("hex")
    .slice(0, 16);
  const file = `${hash}.webp`;
  const result = await sharp(input)
    .rotate()
    .resize({ width, height: width, fit: "inside", withoutEnlargement: true })
    .webp({ quality: 82, effort: 5 })
    .toBuffer({ resolveWithObject: true });
  await writeFile(path.join(output, file), result.data);
  manifest[source] = {
    src: `images/previews/${file}`,
    width: result.info.width,
    height: result.info.height,
  };
  originalBytes += (await stat(original)).size;
  previewBytes += result.data.length;
}
await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
const currentFiles = new Set(Object.values(manifest).map((image) => image.src));
for (const previous of Object.values(previousManifest)) {
  // Only remove files previously generated by this script in its own directory.
  if (
    /^images\/previews\/[a-f0-9]{16}\.webp$/.test(previous.src) &&
    !currentFiles.has(previous.src)
  ) {
    await unlink(path.join(output, path.basename(previous.src))).catch(
      (error) => {
        if (error.code !== "ENOENT") throw error;
      },
    );
  }
}
console.log(
  `${originals.length} previews: ${(originalBytes / 1024 / 1024).toFixed(2)} MB → ${(previewBytes / 1024 / 1024).toFixed(2)} MB (${(100 - (previewBytes / originalBytes) * 100).toFixed(1)}% smaller)`,
);
